// Makes the extension's icons from the CodeGraph logo (../assets/logo.svg), so that they show the same picture:
//   media/icon.svg      a copy of the logo.
//   media/icon.png      the logo at 256 px, for the Extensions view and the Marketplace. vsce refuses an SVG icon.
//   media/activity.svg  the activity bar icon. VS Code draws it as a CSS mask in one theme colour, thus this file is
//                       the logo with white marks and a black tile, used as a luminance mask.
//
// Usage: node scripts/icons.js --browser <path to Chrome, Edge or chrome-headless-shell>
// The PNG is a screenshot from the Chromium that you give, the same engine that VS Code uses to show the icon.
// The unit test src/test/unit/icons.test.ts makes sure that the three files agree with the logo.
'use strict';
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const extensionDir = path.resolve(__dirname, '..');
const logoFile = path.resolve(extensionDir, '..', 'assets', 'logo.svg');
const pngSize = 256;

/** The logo text with LF line ends, the form that the repository keeps. */
function readLogo() {
  return fs.readFileSync(logoFile, 'utf8').replace(/\r\n/g, '\n');
}

/** The SHA-256 of the logo text, which icon.png records in its "Source" text chunk. */
function logoHash(logo) {
  return crypto.createHash('sha256').update(logo).digest('hex');
}

/** The colours of the logo in the one-colour mask: the marks show, the tile and the node outlines do not. */
const maskColours = { '#00C9B1': '#FFFFFF', '#FFD166': '#FFFFFF', '#14263B': '#000000', '#0D1B2A': '#000000' };

/** The activity bar icon: the logo body, with the mask colours, as the luminance mask of one filled square. */
function activitySvg(logo) {
  const start = logo.indexOf('  <defs>');
  const end = logo.lastIndexOf('</svg>');
  if (start < 0 || end < 0) throw new Error('assets/logo.svg has no <defs> or no </svg>');
  let body = logo.slice(start, end).replace(/#[0-9A-Fa-f]{6}/g, (c) => {
    const to = maskColours[c.toUpperCase()];
    if (!to) throw new Error(`assets/logo.svg uses ${c}, which has no mask colour in scripts/icons.js`);
    return to;
  });
  body = body.replace(/\s+$/, '').split('\n').map((line) => (line ? `  ${line}` : line)).join('\n');
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="24" height="24">',
    '  <!-- Made by scripts/icons.js from assets/logo.svg. Do not edit this file: change the logo and run the script. -->',
    '  <!-- VS Code draws this file as a mask in the theme colour. The mask is the logo: white marks on a black tile. -->',
    '  <mask id="logo" maskUnits="userSpaceOnUse" x="0" y="0" width="128" height="128">',
    body,
    '  </mask>',
    '  <rect width="128" height="128" fill="#D7DAE0" mask="url(#logo)"/>',
    '</svg>',
    '',
  ].join('\n');
}

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** The PNG chunks as { type, data } in file order. */
function pngChunks(png) {
  if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error('not a PNG file');
  const chunks = [];
  for (let at = 8; at < png.length;) {
    const length = png.readUInt32BE(at);
    chunks.push({ type: png.toString('latin1', at + 4, at + 8), data: png.subarray(at + 8, at + 8 + length) });
    at += 12 + length;
  }
  return chunks;
}

/** The width, the height and the "Source" text of a PNG file. */
function pngInfo(png) {
  const chunks = pngChunks(png);
  const ihdr = chunks[0].data;
  const text = chunks.find((c) => c.type === 'tEXt' && c.data.toString('latin1').startsWith('Source\0'));
  return {
    width: ihdr.readUInt32BE(0),
    height: ihdr.readUInt32BE(4),
    colourType: ihdr[9],
    source: text ? text.data.toString('latin1').slice('Source\0'.length) : undefined,
  };
}

/** The PNG with one "Source" text chunk after IHDR. The text does not change the pixels. */
function withSource(png, source) {
  const chunk = (type, data) => {
    const head = Buffer.alloc(8);
    head.writeUInt32BE(data.length, 0);
    head.write(type, 4, 'latin1');
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
    return Buffer.concat([head, data, crc]);
  };
  const parts = [png.subarray(0, 8)];
  for (const c of pngChunks(png)) {
    if (c.type === 'tEXt' && c.data.toString('latin1').startsWith('Source\0')) continue;
    parts.push(chunk(c.type, c.data));
    if (c.type === 'IHDR') parts.push(chunk('tEXt', Buffer.from(`Source\0${source}`, 'latin1')));
  }
  return Buffer.concat(parts);
}

function sourceText(logo) {
  return `assets/logo.svg sha256 ${logoHash(logo)}`;
}

/** Renders the logo at 256 px with a Chromium browser, on a clear background. */
function renderPng(browser, logo) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'codegraph-icon-'));
  try {
    const page = path.join(dir, 'icon.html');
    const shot = path.join(dir, 'icon.png');
    const src = `data:image/svg+xml;base64,${Buffer.from(logo).toString('base64')}`;
    fs.writeFileSync(page, '<!doctype html><html><head><style>html,body{margin:0;padding:0;background:transparent;overflow:hidden}</style></head>'
      + `<body><img src="${src}" style="display:block;width:${pngSize}px;height:${pngSize}px"></body></html>`);
    execFileSync(browser, ['--headless', '--disable-gpu', '--hide-scrollbars', '--force-color-profile=srgb',
      '--default-background-color=00000000', `--window-size=${pngSize},${pngSize}`, `--user-data-dir=${path.join(dir, 'profile')}`,
      `--screenshot=${shot}`, `file:///${page.replace(/\\/g, '/').replace(/^\//, '')}`], { stdio: 'ignore', timeout: 120000 });
    if (!fs.existsSync(shot)) throw new Error(`${browser} made no screenshot. Try Chrome or chrome-headless-shell.`);
    const png = fs.readFileSync(shot);
    const info = pngInfo(png);
    if (info.width !== pngSize || info.height !== pngSize) throw new Error(`the browser made a ${info.width}x${info.height} PNG, not ${pngSize}x${pngSize}`);
    if (info.colourType !== 6) throw new Error('the browser made a PNG with no alpha channel');
    return withSource(png, sourceText(logo));
  } finally {
    fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5 });
  }
}

function main(argv) {
  const at = argv.indexOf('--browser');
  const browser = at >= 0 ? argv[at + 1] : process.env.CHROME;
  if (!browser) throw new Error('Give the path to Chrome, Edge or chrome-headless-shell with --browser, or set CHROME.');
  const logo = readLogo();
  const media = path.join(extensionDir, 'media');
  const png = renderPng(browser, logo);
  fs.writeFileSync(path.join(media, 'icon.svg'), logo);
  fs.writeFileSync(path.join(media, 'activity.svg'), activitySvg(logo));
  fs.writeFileSync(path.join(media, 'icon.png'), png);
  console.log(`Made media/icon.svg, media/activity.svg and media/icon.png from ${sourceText(logo)}.`);
}

module.exports = { readLogo, logoHash, activitySvg, pngInfo, sourceText };
if (require.main === module) main(process.argv.slice(2));
