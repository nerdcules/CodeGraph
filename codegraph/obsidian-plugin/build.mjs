// Bundles src/main.js and the lib/ modules it requires into the single main.js Obsidian loads. No dependencies:
// each local module is wrapped in a function and its relative requires point at the wrapped copy; `obsidian`,
// `electron` and Node built-ins stay real requires, which Obsidian provides.
//
//   node build.mjs            writes main.js
//   node build.mjs --check    fails when main.js is out of date

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const entry = 'src/main.js';
const REQUIRE = /require\((['"])(\.{1,2}\/[^'"]+)\1\)/g;

const modules = new Map();
function collect(file) {
  if (modules.has(file)) {
    return;
  }

  const source = readFileSync(join(root, file), 'utf8');
  modules.set(file, null);
  const rewritten = source.replace(REQUIRE, (_, quote, spec) => {
    const target = relative(root, resolve(join(root, dirname(file)), spec)).replace(/\\/g, '/');
    collect(target);
    return `__require(${JSON.stringify(target)})`;
  });
  modules.set(file, rewritten);
}

collect(entry);

const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'));
let out = `/* CodeGraph for Obsidian ${manifest.version}. Generated by build.mjs from src/ and lib/; edit those, not this file. */\n'use strict';\n`;
out += 'const __defs = {\n';
for (const [file, source] of modules) {
  out += `${JSON.stringify(file)}: function (module, exports, __require) {\n${source}\n},\n`;
}

out += `};
const __cache = {};
function __require(name) {
  if (__cache[name]) return __cache[name].exports;
  const module = { exports: {} };
  __cache[name] = module;
  __defs[name](module, module.exports, __require);
  return module.exports;
}
module.exports = __require(${JSON.stringify(entry)});
`;

const target = join(root, 'main.js');
if (process.argv.includes('--check')) {
  // A checkout with autocrlf has CRLF in main.js; the bundle is the same bundle.
  if (!existsSync(target) || readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== out) {
    console.error('main.js is out of date: run node build.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`main.js: ${modules.size} modules, ${out.length} bytes`);
}
